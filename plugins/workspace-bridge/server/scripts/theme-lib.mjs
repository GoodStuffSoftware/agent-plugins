// Reads a theme directory and checks it. Shared by build-theme.mjs and snapshots.mjs.
//
// theme/
//   theme.css        optional  CSS appended after the base sheet
//   name.txt         optional  product name for the header (one line, at most 40 characters)
//   assets/*.svg     optional  images; assets/logo.svg is the header logo, logo-dark.svg its dark variant
//   assets/*.woff2   optional  fonts, used from theme.css with url(/theme/assets/<name>)

import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

export const LIMITS = {
  css: 64 * 1024,
  svg: 128 * 1024,
  woff2: 300 * 1024,
  total: 1536 * 1024,
  name: 40,
};

const NAME = /^[a-z0-9][a-z0-9._-]{0,63}$/;

function fail(msg) {
  throw new Error(`theme: ${msg}`);
}

/** The theme in `dir` as the data the Worker bundles; throws on anything outside the contract. */
export function readTheme(dir) {
  if (!existsSync(dir) || !statSync(dir).isDirectory()) fail(`${dir} is not a directory`);
  const known = new Set(["theme.css", "name.txt", "assets", "README.md"]);
  for (const entry of readdirSync(dir)) {
    if (!known.has(entry)) fail(`unexpected ${entry} (allowed: theme.css, name.txt, assets/)`);
  }
  let total = 0;
  let css = "";
  const cssPath = join(dir, "theme.css");
  if (existsSync(cssPath)) {
    css = readFileSync(cssPath, "utf8").replaceAll("\r\n", "\n");
    if (css.length > LIMITS.css) fail(`theme.css is over ${LIMITS.css} bytes`);
    if (/@import/i.test(css))
      fail("theme.css must not use @import (serve everything from assets/)");
    if (/<\/style/i.test(css)) fail("theme.css must not contain </style");
    if (/url\(\s*["']?\s*(?:https?:)?\/\//i.test(css)) {
      fail("theme.css must not load from another origin; put the file in assets/");
    }
    total += css.length;
  }
  let name = "";
  const namePath = join(dir, "name.txt");
  if (existsSync(namePath)) {
    name = readFileSync(namePath, "utf8").trim();
    if (name.length > LIMITS.name || /[\r\n]/.test(name)) {
      fail(`name.txt must be one line of at most ${LIMITS.name} characters`);
    }
  }
  const assets = {};
  const assetDir = join(dir, "assets");
  if (existsSync(assetDir)) {
    for (const file of readdirSync(assetDir).sort()) {
      if (!NAME.test(file)) fail(`assets/${file}: use lowercase letters, digits, . _ - only`);
      const bytes = readFileSync(join(assetDir, file));
      if (file.endsWith(".svg")) {
        if (bytes.length > LIMITS.svg) fail(`assets/${file} is over ${LIMITS.svg} bytes`);
        const text = bytes.toString("utf8").replaceAll("\r\n", "\n");
        if (/<script|<foreignObject|\son[a-z]+\s*=|javascript:|<!ENTITY/i.test(text)) {
          fail(`assets/${file}: scripts, event handlers and foreignObject are not allowed`);
        }
        if (/(?:xlink:)?href\s*=\s*["']\s*(?:https?:)?\/\//i.test(text)) {
          fail(`assets/${file}: no references to other origins`);
        }
        assets[file] = { type: "image/svg+xml", text };
      } else if (file.endsWith(".woff2")) {
        if (bytes.length > LIMITS.woff2) fail(`assets/${file} is over ${LIMITS.woff2} bytes`);
        if (bytes.subarray(0, 4).toString("latin1") !== "wOF2") fail(`assets/${file} is not woff2`);
        assets[file] = { type: "font/woff2", base64: bytes.toString("base64") };
      } else {
        fail(`assets/${file}: only .svg and .woff2 files are allowed`);
      }
      total += bytes.length;
    }
  }
  if (total > LIMITS.total) fail(`the theme is over ${LIMITS.total} bytes in total`);
  return { css, name, assets };
}

/** The TypeScript module the Worker imports. Stable output, so a check can compare it. */
export function renderModule(theme) {
  return `// Generated by scripts/build-theme.mjs from theme/. Do not edit.
import type { ThemeData } from "./theme";

export const THEME_DATA: ThemeData = ${JSON.stringify(theme, null, 2)};
`;
}
